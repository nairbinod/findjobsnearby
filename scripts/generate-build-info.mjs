import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";

// Regenerates lib/build-info.ts from the actual last git commit, run before
// every dev/build via the npm scripts below -- this used to be a hand-typed
// constant that only updated when someone remembered to edit it, which is
// why the footer sat frozen on "September 3" no matter how many times the
// site actually shipped changes since.
function run(command, fallback) {
  try {
    return execSync(command, { encoding: "utf8" }).trim();
  } catch {
    return fallback;
  }
}

const shortSha = run("git rev-parse --short HEAD", "dev");
const commitDateIso = run("git log -1 --format=%cI", "");
const lastUpdated = new Date(commitDateIso || Date.now()).toLocaleDateString("en-US", {
  month: "long",
  day: "numeric",
  year: "numeric",
});

const content = `// Auto-generated by scripts/generate-build-info.mjs before every dev/build
// run -- do not hand-edit, changes here will be overwritten.
export const buildNumber = ${JSON.stringify(shortSha)};
export const lastUpdated = ${JSON.stringify(lastUpdated)};
`;

writeFileSync(new URL("../lib/build-info.ts", import.meta.url), content);
console.log(`Generated lib/build-info.ts (build ${shortSha}, updated ${lastUpdated})`);
